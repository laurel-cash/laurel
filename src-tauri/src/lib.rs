#[cfg_attr( mobile, tauri::mobile_entry_point )]
pub fn Sys_Run() {
	let specta = Sys_Specta();

	#[cfg( all( debug_assertions, desktop ) )]
	Sys_Bindings( BINDINGS_PATH ).expect( "Sys_Run: writing ui bindings" );

	let builder = tauri::Builder::default();
	#[cfg( desktop )]
	let builder = builder
		// first: a second copy of Laurel only brings this one forward. Two
		// engines saving the same wallet file, or a second start cleaning a
		// live browser's caches, can't happen
		.plugin( tauri_plugin_single_instance::init( |app, _args, _cwd| {
			if let Some( win ) = app.get_webview_window( MAIN_WINDOW ) {
				let _ = win.unminimize();
				let _ = win.show();
				let _ = win.set_focus();
			}
		} ) );

	#[cfg( target_os = "android" )]
	let builder = builder.plugin( w_mobile::M_Plugin() ).plugin( w_documents::Doc_Plugin() );

	builder.plugin( Sys_Logger() )
		.plugin( tauri_plugin_opener::init() )
		.plugin( tauri_plugin_notification::init() )
		.plugin( tauri_plugin_dialog::init() )		// the sync folder's picker, opened from Rust only
		.invoke_handler( specta.invoke_handler() )
		.setup( move |app| {
			specta.mount_events( app );
			log::info!( "Sys_Run: Laurel {} ({}, {})", env!( "CARGO_PKG_VERSION" ), w_local::NETWORKS_MARK, w_probe::PROBE_MARK );
			// before anything reads them: the folders an older Laurel kept under its old identifier
			let data = Sys_MoveOld( app.path().app_data_dir()?, true );
			let _ = Sys_MoveOld( app.path().app_local_data_dir()?, false );
			w_storage::Sto_Init( data.clone(), app.path().app_local_data_dir()?.join( "EBWebView" ), app.path().app_log_dir()? );
			w_main::W_Init( data );
			w_repeat::Rp_Watch( app.handle().clone() );		// says when a repeating payment comes due
			w_alert::Al_Watch( app.handle().clone() );		// and when the price crosses an alert
			w_folder::F_Watch( app.handle().clone() );		// and keeps the person's computers alike (docs/SYNC.md)
			w_storage::Sto_Janitor();		// before the window: the browser holds its caches open
			Sys_MainWindow( app )?;
			#[cfg( feature = "kdf-probe" )]
			w_probe::P_Start();		// a test build's only (w_probe.rs)
			Ok( () )
		} )
		.build( tauri::generate_context!() )
		.expect( "Sys_Run: error while building laurel" )
		.run( |app, event| {
			// hold the exit until every wallet has been written out
			match event {
				// the window's close: it stays up, saying so, while the wallets are written
				tauri::RunEvent::WindowEvent { label, event: tauri::WindowEvent::CloseRequested { api, .. }, .. } if label == MAIN_WINDOW => {
					api.prevent_close();
					Sys_Close( app, 0 );
				}
				tauri::RunEvent::ExitRequested { api, code, .. } => {
					if ( !sys_exiting.load( Ordering::SeqCst ) ) {
						api.prevent_exit();
						Sys_Close( app, code.unwrap_or( 0 ) );
					}
				}
				#[cfg( target_os = "ios" )]
				tauri::RunEvent::WindowEvent { event: tauri::WindowEvent::Suspended, .. } => {
					w_mobile::M_Hidden( app.clone() );
				}
				_ => {}
			}
		} );
}


