/*
==================
Sys_Bindings

Writes src/bindings.ts. Runs on every debug start, so the ui is never
compiled against yesterday's types.
==================
*/
pub fn Sys_Bindings( path: &str ) -> Result< (), String > {
	Sys_Specta()
		.export( Typescript::default().header( BINDINGS_HEADER ), path )
		.map_err( |e| e.to_string() )
}

/*
==================
Sys_Logger

One small log file, so a problem in the field can be found afterwards.
Capped (LOG_MAX_BYTES, plus one older file): a log must never become the
disk-space problem Laurel set out not to have. Addresses, transaction ids
and keys are masked in every line, whoever wrote it (w_log.rs).
==================
*/
fn Sys_Logger() -> tauri::plugin::TauriPlugin< tauri::Wry > {
	use tauri_plugin_log::{ RotationStrategy, Target, TargetKind };

	tauri_plugin_log::Builder::new()
		.clear_targets()
		.target( Target::new( TargetKind::LogDir { file_name: Some( "laurel".into() ) } ) )
		// the terminal only while developing: a release's stdout is the phone's logcat, readable over adb (W1-04)
		.targets( if cfg!( debug_assertions ) { vec![ Target::new( TargetKind::Stdout ) ] } else { vec![] } )
		.level( log::LevelFilter::Info )
		.level_for( "tonic", log::LevelFilter::Warn )
		.level_for( "h2", log::LevelFilter::Warn )
		.level_for( "hyper", log::LevelFilter::Warn )
		.level_for( "hyper_util", log::LevelFilter::Warn )
		.level_for( "rustls", log::LevelFilter::Warn )
		.level_for( "tower", log::LevelFilter::Warn )
		.max_file_size( LOG_MAX_BYTES )
		// the one door to the file: every line, the engine's too, masked (w_log.rs)
		.format( |out, message, record| {
			out.finish( format_args!(
				"{}[{}][{}] {}",
				tauri_plugin_log::TimezoneStrategy::UseLocal.get_now(),
				record.level(),
				record.target(),
				w_log::Com_LogSafe( &message.to_string() ),
			) )
		} )
		.rotation_strategy( RotationStrategy::KeepSome( 1 ) )
		.build()
}

/*
==================
Sys_MainWindow

Made here, not from tauri.conf.json directly, so it opens after the
janitor and with the browser settings that keep its caches off disk
==================
*/
// the identifier before com.rptxsoftware.wallet (2026-10-03, for Google Play:
// a package name says nothing of the product, and never changes)
const OLD_IDENTIFIER: &str = "cash.laurel.wallet";

/*
==================
Sys_MoveOld

A folder an older Laurel kept under its old identifier, moved once into
the new one beside it. whole (the data: wallets, the key file, settings):
all or nothing, never over what's there; if it can't, the old folder
stays in use, so nothing is lost, and the move is tried at the next start.
Not whole (the browser's storage, logs): what moves, moves
==================
*/
fn Sys_MoveOld( new: std::path::PathBuf, whole: bool ) -> std::path::PathBuf {
	let Some( old ) = new.parent().map( |d| d.join( OLD_IDENTIFIER ) ) else {
		return new;
	};
	if ( old == new || !old.exists() ) {
		return new;
	}
	match w_disk::Com_MoveInto( &old, &new, whole ) {
		Ok( () ) => {
			log::info!( "Sys_MoveOld: moved the folder of the old identifier" );
			new
		}
		Err( e ) if whole => {
			log::warn!( "Sys_MoveOld: kept using the folder of the old identifier: {}", e.to_string() );
			old
		}
		Err( e ) => {
			log::warn!( "Sys_MoveOld: left some of the old identifier's folder: {}", e.to_string() );
			new
		}
	}
}

fn Sys_MainWindow( app: &tauri::App ) -> tauri::Result< () > {
	let config = app.config().app.windows.iter()
		.find( |w| w.label == MAIN_WINDOW )
		.cloned()
		.expect( "Sys_MainWindow: tauri.conf.json has no main window" );

	let builder = tauri::WebviewWindowBuilder::from_config( app.handle(), &config )?;
	#[cfg( windows )]
	let builder = builder.additional_browser_args( w_storage::STO_BROWSER_ARGS );
	builder.build()?;
	Ok( () )
}

/*
==================
Sys_Close

The one way Laurel closes: the window says it's saving, every engine
stops and every wallet is written (w_main::W_Shutdown), within a budget
built from its parts (SHUTDOWN_BUDGET_SECS), then the process exits.
Once only: a second request while saving is the same close.
On Android it comes when the system ends the activity (swiped away,
reclaimed), and the process then ends as Android ends one (Sys_End)
==================
*/
fn Sys_Close( app: &tauri::AppHandle, code: i32 ) {
	if ( sys_exiting.swap( true, Ordering::SeqCst ) ) {
		return;
	}
	let _ = w_local::closingEvent_t {}.emit( app );
	let app = app.clone();
	tauri::async_runtime::spawn( async move {
		if ( tokio::time::timeout( Duration::from_secs( w_engine::SHUTDOWN_BUDGET_SECS ), w_main::W_Shutdown() ).await.is_err() ) {
			log::warn!( "Sys_Close: saving took longer than {} s; closing anyway", w_engine::SHUTDOWN_BUDGET_SECS );
		}
		#[cfg( target_os = "android" )]
		{
			let _ = app;		// Android: the process ends here, saved (Sys_End)
			Sys_End( code );
		}
		#[cfg( not( target_os = "android" ) )]
		app.exit( code );
	} );
}

/*
==================
Sys_End

Android: the process ends where it stands, as Android itself ends one,
without the C library's exit handlers. A normal exit (app.exit, which
tao's Android loop ends in std::process::exit) runs C++ static
destructors while Android's render threads (hwui) still wait on their
locks, and one aborts: "pthread_mutex_lock called on a destroyed mutex"
(Test Lab, Pixel 7, 0.1.4), a crash in Play's vitals for every close.
The wallets are written by now (Sys_Close)
==================
*/
#[cfg( target_os = "android" )]
pub fn Sys_End( code: i32 ) -> ! {
	log::info!( "Sys_End: {code}" );
	log::logger().flush();		// _exit writes nothing still buffered: these are the lines a bad close leaves
	// SAFETY: _exit only ends the process; nothing of it is touched again
	unsafe { libc::_exit( code ) }
}

