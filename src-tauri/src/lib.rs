#[cfg( test )]
mod tests {
	use super::*;

	/*
	==================
	bindings_are_fresh

	Fails when someone changed a type or command in rust and didn't run
	a debug build to regenerate the ui bindings
	==================
	*/
	/*
	==================
	write_bindings

	`npm run bindings`: regenerates src/bindings.ts without starting the app
	==================
	*/
	#[test]
	#[ignore]
	fn write_bindings() {
		Sys_Bindings( BINDINGS_PATH ).expect( "export" );
	}

	#[test]
	fn bindings_are_fresh() {
		let fresh = std::env::temp_dir().join( "laurel-bindings-check.ts" );
		Sys_Bindings( fresh.to_str().unwrap() ).expect( "export" );

		let norm = |s: String| s.replace( "\r\n", "\n" );
		let want = norm( std::fs::read_to_string( &fresh ).unwrap() );
		let have = norm( std::fs::read_to_string( BINDINGS_PATH ).unwrap_or_default() );

		assert!( want == have, "src/bindings.ts is stale: run a debug build (npm run tauri dev) to regenerate it" );
	}
}
