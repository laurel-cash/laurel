// EN is English; its shape is text_t, the contract every language keeps:
// a translation is one object of text_t (the compiler refuses a missing
// key or a message with other parameters), registered in LANGUAGES below
// and ui_locale.ts's LOCALES. A sentence is whole: a language may put its
// parts in any order, so what goes inside one is a parameter or a {slot}
// (UI_Slots), never a sentence built from pieces on screen. Counting is a
// language's own: plural() (Intl.PluralRules), never "n === 1 ?"
// (check_owners). Engine errors are here too, by code (errors, below).

