// the coin's name on the open network, asked each time a sentence is built:
// the network is read at start, after this file is loaded
function Unit(): string {
	return Com_Unit( useStore.getState().network );
}

// on a phone: a finger taps, and there are no keyboard shortcuts to name
function Phone(): boolean {
	return useStore.getState().constants?.mobile === true;
}

// English's plural forms: one and other (Intl.PluralRules); and its lists: "A, B, and C"
const plural = Com_Plural( "en" );
const list = Com_ListIn( "en" );

// "About 5 minutes left": it said "About 1 minutes left" once a minute was left
function AboutLeft( n: number, unit: "minute" | "hour" ): string {
	return unit === "minute"
		? plural( n, { one: "About 1 minute left", other: `About ${n} minutes left` } )
		: plural( n, { one: "About 1 hour left", other: `About ${n} hours left` } );
}

// an auto-lock time, wherever a sentence names one
function Minutes( m: number ): string {
	return m === 60 ? "1 hour" : plural( m, { one: "1 minute", other: `${m} minutes` } );
}

