// make_errors.mjs -- English for Rust's errors, from Rust, once
//
// Each werr_t (src-tauri/src/w_local.rs) says what went wrong in its
// #[error( "..." )], and the screen said it again in ui_text.ts: two copies
// of every sentence, kept apart by nothing. Now Rust's is the only English:
// this writes it to src/generated/errors.ts (ERRORS_EN), which ui_text.ts
// spreads into English's errors. A translation writes its own, keyed the same.
// Run by npm run bindings; check_owners fails when it is stale.
//
//   node scripts/make_errors.mjs           write it
//   node scripts/make_errors.mjs --check   say whether it is current

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const RUST	= "src-tauri/src/w_local.rs";
const OUT	= "src/generated/errors.ts";

// the one that only wraps another: the screen says the inner one's
const SKIP = [ "WERR_TYPED" ];

/*
==================
Com_ErrorsEn

Every error's name and its English, as Rust says it: {0}, {1} are its
values (werr_t::Args sends them, check_owners holds the two together)
==================
*/
export function Com_ErrorsEn() {
	const rs = readFileSync( RUST, "utf8" ).replace( /\r\n/g, "\n" );
	const start = rs.indexOf( "pub enum werr_t {" );
	const body = rs.slice( start, rs.indexOf( "\n}\n", start ) );
	const errors = [];
	for ( const m of body.matchAll( /#\[error\( "((?:[^"\\]|\\.)*)" \)\][^\n]*\n(?:\t#\[[^\n]*\n)*\t(WERR_\w+)/g ) ) {
		if ( !SKIP.includes( m[2] ) ) {
			errors.push( [ m[2], m[1].replace( /\\"/g, "\"" ) ] );
		}
	}
	return errors;
}

export function Com_ErrorsFile() {
	const lines = Com_ErrorsEn().map( ( [ name, text ] ) => `\t${name}: ${JSON.stringify( text )},` );
	return `// generated by scripts/make_errors.mjs from src-tauri/src/w_local.rs (werr_t's #[error]): never edit
export const ERRORS_EN = {
${lines.join( "\n" )}
} as const;
`;
}

if ( process.argv[1] === fileURLToPath( import.meta.url ) ) {
	const want = Com_ErrorsFile();
	if ( process.argv.includes( "--check" ) ) {
		let have = "";
		try {
			have = readFileSync( OUT, "utf8" ).replace( /\r\n/g, "\n" );
		} catch {
			// none yet: stale
		}
		if ( have !== want ) {
			console.error( `make_errors: ${OUT} is out of date: run npm run bindings` );
			process.exit( 1 );
		}
		console.log( `make_errors: ${OUT} is current` );
	} else {
		writeFileSync( OUT, want );
		console.log( `make_errors: ${Com_ErrorsEn().length} errors to ${OUT}` );
	}
}
